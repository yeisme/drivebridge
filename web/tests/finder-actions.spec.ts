import { test, expect } from "@playwright/test";
import path from "node:path";

test("Finder context menus create nested folders and text files without overwriting", async ({ page }) => {
  await page.setViewportSize({width:1440,height:1000});
  await page.goto("/");
  await page.locator("#login-key").fill("dbu_"+"1".repeat(96));
  await page.getByRole("button",{name:"登录",exact:true}).click();
  await expect(page.getByRole("button",{name:"账户菜单"})).toBeVisible();
  // This key starts without a drive in the standard fixture.
  await page.evaluate(async()=>{
    const me=(await(await fetch("/api/v1/me")).json()).data;
    const response=await fetch("/api/v1/spaces",{method:"POST",headers:{"Content-Type":"application/json","X-CSRF-Token":me.csrf_token},body:JSON.stringify({name:"Context files",connection_id:"platform"})});
    if(!response.ok)throw new Error("Fixture space failed");
  });
  await page.reload();
  await page.getByRole("button",{name:"打开网盘 Context files",exact:true}).click();
  await page.locator(".empty").click({button:"right"});
  await page.getByRole("menuitem",{name:"新建文件夹",exact:true}).click();
  let dialog=page.getByRole("dialog",{name:"新建文件夹",exact:true});
  await dialog.getByRole("textbox",{name:"名称",exact:true}).fill("项目/资料");
  await expect(dialog.getByRole("button",{name:"确认",exact:true})).toBeDisabled();
  await dialog.getByRole("checkbox", { name: "创建多级目录（例如：2026/参考资料）" }).check();
  await dialog.getByRole("checkbox", { name: "创建后打开文件夹" }).check();
  await dialog.getByRole("button",{name:"确认",exact:true}).click();
  await expect(dialog).toHaveCount(0);
  await expect(page.locator(".finder-status")).toContainText("0 个文件");
  await page.locator(".empty").click({button:"right"});
  await page.getByRole("menuitem",{name:"新建文本文件",exact:true}).click();
  dialog=page.getByRole("dialog",{name:"新建文本文件",exact:true});
  await expect(dialog).toContainText("项目/资料");
  await dialog.getByRole("textbox",{name:"名称",exact:true}).fill("笔记.txt");
  await dialog.getByLabel("文件内容").fill("需要保留的文件内容\n");
  await dialog.getByRole("button",{name:"确认",exact:true}).click();
  await expect(page.locator(".finder-file").filter({hasText:"笔记.txt"})).toBeVisible();
  await page.getByRole("button",{name:"新建",exact:true}).click();
  await page.getByRole("menuitem",{name:"新建文件",exact:true}).click();
  dialog=page.getByRole("dialog",{name:"新建文本文件",exact:true});
  await dialog.getByRole("textbox",{name:"名称",exact:true}).fill("空白.txt");
  await dialog.getByRole("button",{name:"确认",exact:true}).click();
  const blank=page.locator(".finder-file").filter({hasText:"空白.txt"});
  await expect(blank).toContainText("0 B");
  await blank.locator(".finder-name").dblclick();
  const quicklook=page.locator(".quicklook-dialog");
  await expect(quicklook.getByRole("complementary",{name:"预览文件列表与信息"})).toBeVisible();
  await expect(quicklook.getByRole("navigation",{name:"当前文件列表"}).getByRole("button")).toHaveCount(2);
  await quicklook.getByRole("navigation",{name:"当前文件列表"}).getByRole("button").first().click();
  const firstTitle=await quicklook.locator("header h2").textContent();
  await page.keyboard.press("ArrowDown");
  await expect(quicklook.locator("header h2")).not.toHaveText(firstTitle!);
  await page.keyboard.press("ArrowUp");
  await expect(quicklook.locator("header h2")).toHaveText(firstTitle!);
  await page.screenshot({path:path.join(process.env.DRIVEBRIDGE_EVIDENCE_ARTIFACTS||"temp/browser-artifacts","quicklook.png")});
  await page.setViewportSize({width:390,height:844});
  // Base UI positions the popup asynchronously; wait for it to settle at the new viewport.
  await expect.poll(async () => {
    const b=await quicklook.boundingBox();
    return !!b && b.x+b.width<=390 && b.y+b.height<=844;
  }).toBe(true);
  const qbounds=await quicklook.boundingBox();
  expect(qbounds!.x+qbounds!.width).toBeLessThanOrEqual(390);
  expect(qbounds!.y+qbounds!.height).toBeLessThanOrEqual(844);
  await page.screenshot({path:path.join(process.env.DRIVEBRIDGE_EVIDENCE_ARTIFACTS||"temp/browser-artifacts","quicklook-mobile.png")});
  await page.setViewportSize({width:1440,height:1000});
  await quicklook.getByRole("button",{name:"关闭",exact:true}).click();
  await blank.locator(".finder-name").press("Shift+F10");
  await page.getByRole("menuitem",{name:"查看元数据",exact:true}).click();
  await expect(page.getByRole("complementary",{name:"文件检查器"})).toContainText("版本标识");
  await expect(page.getByRole("complementary",{name:"文件检查器"})).toContainText("空文本文件 · 0 B");
  await page.getByRole("button",{name:"关闭检查器",exact:true}).click();
  await blank.click({button:"right"});
  await page.getByRole("menuitem",{name:"重命名",exact:true}).click();
  dialog=page.getByRole("dialog",{name:"重命名",exact:true});
  await dialog.getByRole("textbox",{name:"名称",exact:true}).fill("笔记.txt");
  await dialog.getByRole("button",{name:"确认",exact:true}).click();
  await expect(dialog.getByRole("alert")).toBeVisible();
  await dialog.getByRole("textbox",{name:"名称",exact:true}).fill("空白归档.txt");
  await dialog.getByRole("button",{name:"确认",exact:true}).click();
  await expect(dialog).toHaveCount(0);
  await expect(page.locator(".finder-file").filter({hasText:"笔记.txt"})).toBeVisible();
  await page.setViewportSize({width:390,height:844});
  await page.getByRole("button",{name:"更多操作 项目/资料/空白归档.txt",exact:true}).click();
  const menu=page.getByRole("menu",{name:"文件操作菜单"});
  const bounds=await menu.boundingBox();
  expect(bounds!.x).toBeGreaterThanOrEqual(0);
  expect(bounds!.x+bounds!.width).toBeLessThanOrEqual(390);
  expect(bounds!.y+bounds!.height).toBeLessThanOrEqual(844);
  await page.keyboard.press("ArrowDown");
  await expect(page.getByRole("menuitem",{name:"查看元数据",exact:true})).toBeFocused();
  const artifacts=process.env.DRIVEBRIDGE_EVIDENCE_ARTIFACTS||"temp/browser-artifacts";
  await page.screenshot({path:path.join(artifacts,"finder-menu-mobile.png"),fullPage:false});
  await page.keyboard.press("Escape");
  await expect(menu).toHaveCount(0);
  await page.setViewportSize({width:1440,height:1000});
  await page.getByRole("region",{name:"文件浏览"}).focus();
  await page.keyboard.press("Shift+F10");
  await page.getByRole("menuitem",{name:"目录信息",exact:true}).click();
  await expect(page.getByRole("dialog",{name:"目录信息"})).toContainText("直属文件");
  await page.screenshot({path:path.join(artifacts,"finder-directory-metadata.png"),fullPage:true});
  await page.getByRole("dialog",{name:"目录信息"}).getByRole("button",{name:"关闭",exact:true}).click();
  await page.locator(".finder-file").filter({hasText:"笔记.txt"}).locator(".finder-name").click();
  await page.getByRole("region",{name:"文件浏览"}).press("Control+c");
  await expect(page.locator(".clipboard-bar")).toContainText("已复制 1 项");
  await page.getByRole("button",{name:"创建副本",exact:true}).click();
  await expect(page.locator(".finder-file").filter({hasText:"笔记 (2).txt"})).toBeVisible();
  await page.locator(".finder-file").filter({hasText:"空白归档.txt"}).locator(".finder-name").click();
  await page.getByRole("region",{name:"文件浏览"}).press("Delete");
  const trash=page.getByRole("dialog",{name:"移入回收站",exact:true});
  await expect(trash).toContainText("空白归档.txt");
  await trash.getByRole("button",{name:"取消",exact:true}).click();
  await expect(page.locator(".finder-file").filter({hasText:"空白归档.txt"})).toBeVisible();
  await page.getByRole("navigation",{name:"目录路径"}).getByRole("button",{name:"全部文件",exact:true}).click();
  const folderRow=page.locator(".finder-folder").filter({hasText:"项目"});
  await folderRow.locator(".finder-name").click();
  await expect(page.locator(".finder-status")).toContainText("文件夹");
  await page.getByRole("button",{name:"移动到…",exact:true}).click();
  await expect(page.getByRole("tree",{name:"选择目标目录"})).toContainText("根目录");
  await page.getByRole("dialog",{name:"移动文件"}).getByRole("button",{name:"取消",exact:true}).click();
  await page.getByRole("region",{name:"文件浏览"}).press("Control+c");
  await expect(page.locator(".clipboard-bar")).toContainText("已复制");
  await folderRow.getByRole("button",{name:"打开文件夹 项目"}).click();
  await expect(page.locator(".finder-folder").filter({hasText:"资料"})).toBeVisible();
  await page.getByRole("navigation",{name:"目录路径"}).getByRole("button",{name:"全部文件",exact:true}).click();
  await page.getByRole("button",{name:"粘贴到当前目录",exact:true}).click();
  await expect(page.locator(".finder-folder").filter({hasText:"项目 (2)"})).toBeVisible({timeout:15000});
  await page.locator(".clipboard-bar").getByRole("button",{name:"清除",exact:true}).click();
  await page.getByRole("searchbox",{name:"搜索文件"}).fill("笔记");
  await page.getByRole("searchbox",{name:"搜索文件"}).press("Control+c");
  await expect(page.locator(".clipboard-bar")).toHaveCount(0);
});
