import { expect, test } from '@playwright/test';
test.use({ trace: 'off', video: 'off', screenshot: 'off' });
test('trash distinguishes pending and failed reads, then manually recovers real owner rows', async ({ page }) => {
  await page.goto('/'); await page.getByRole('link', { name: '使用账号登录' }).click(); await page.getByRole('link', { name: '以 Alice 登录' }).click();
  await expect(page.getByRole('heading', { name: '我的网盘', exact: true })).toBeVisible();
  const drive = page.getByRole('button', { name: /^打开网盘 / }).first(); await drive.click();
  const name = 'trash-state-' + Date.now() + '.txt';
  await page.locator('input[type=file]').setInputFiles({ name, mimeType: 'text/plain', buffer: Buffer.from('Disposable trash read state') });
  await page.getByRole('button', { name: '详情 ' + name, exact: true }).click();
  await page.getByRole('button', { name: '移入回收站', exact: true }).click();
  let release!: () => void;
  const pending = new Promise<void>(resolve => { release = resolve; });
  let fail = true, calls = 0;
  await page.route('**/api/v1/files?*', async route => {
    if (new URL(route.request().url()).searchParams.get('trash') !== 'true') return route.continue();
    calls++;
    if (calls === 1) await pending;
    if (fail) return route.abort('failed');
    return route.continue();
  });
  const writes: string[] = [];
  page.on('request', request => { if (request.url().includes('/api/v1/') && !['GET', 'HEAD'].includes(request.method())) writes.push(request.method()); });
  await page.getByRole('navigation', { name: '工作区导航' }).getByRole('button', { name: '回收站', exact: true }).click();
  await expect(page.getByText('正在读取回收站…', { exact: true })).toBeVisible();
  await expect(page.getByText('回收站是空的', { exact: true })).toHaveCount(0);
  await expect(page.getByRole('button', { name: '恢复所选', exact: true })).toBeDisabled();
  release();
  await expect(page.getByText(/无法读取回收站/)).toBeVisible();
  await expect(page.getByText('回收站是空的', { exact: true })).toHaveCount(0);
  fail = false; await page.getByRole('button', { name: '重读回收站', exact: true }).click();
  await expect(page.getByRole('button', { name: '恢复 ' + name, exact: true })).toBeVisible();
  await page.getByRole('checkbox', { name: '选择 ' + name, exact: true }).check();
  await expect(page.getByRole('button', { name: '恢复所选', exact: true })).toBeEnabled();
  fail = true; await page.getByRole('button', { name: '重读回收站', exact: true }).click();
  await expect(page.getByText(/无法读取回收站/)).toBeVisible();
  await expect(page.getByRole('button', { name: '恢复 ' + name, exact: true })).toHaveCount(0);
  await expect(page.getByRole('button', { name: '恢复所选', exact: true })).toBeDisabled();
  fail = false; await page.getByRole('button', { name: '重读回收站', exact: true }).click();
  await expect(page.getByRole('checkbox', { name: '选择 ' + name, exact: true })).not.toBeChecked();
  await expect(page.getByRole('button', { name: '永久删除所选', exact: true })).toBeDisabled();
  expect(writes).toEqual([]); expect(calls).toBe(4);
});
