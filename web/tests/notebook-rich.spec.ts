import { expect, test } from '@playwright/test';
import path from 'node:path';

test('fixed Markdown safely renders math and diagrams and rebuilds authorized relations', async ({ page }) => {
  test.setTimeout(120_000);
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.setViewportSize({ width: 1920, height: 1000 });
  await page.goto('/');
  await page.getByRole('link', { name: '使用账号登录' }).click();
  await page.getByRole('link', { name: '以 Alice 登录' }).click();
  const space = await page.evaluate(async () => {
    const me = (await (await fetch('/api/v1/me')).json()).data;
    const response = await fetch('/api/v1/spaces', { method: 'POST', headers: { 'Content-Type': 'application/json', 'X-CSRF-Token': me.csrf_token }, body: JSON.stringify({ name: 'Rich notebook fixture', connection_id: 'platform' }) });
    if (!response.ok) throw new Error('fixture_space_failed');
    return (await response.json()).data.id as string;
  });
  await page.reload();
  await page.getByRole('button', { name: '打开网盘 Rich notebook fixture', exact: true }).click();
  await page.locator('input[type=file]').setInputFiles({ name: 'target.md', mimeType: 'text/markdown', buffer: Buffer.from('# Target\n\nFixed referenced note.') });
  await expect(page.getByRole('button', { name: '详情 target.md', exact: true })).toBeVisible();
  await page.locator('input[type=file]').setInputFiles({ name: 'rich.md', mimeType: 'text/markdown', buffer: Buffer.from('# 阅读与关系\n\n公式 $E=mc^2$。\n\n$$\\frac{a}{b}$$\n\n[关联笔记](target.md#target)\n\n```mermaid\nflowchart LR\n A[固定版本] --> B[人工确认]\n```\n\n```mermaid\n%%{init: {"securityLevel":"loose"}}%%\nflowchart LR\n A --> B\n```') });
  await expect(page.getByRole('button', { name: '详情 rich.md', exact: true })).toBeVisible();
  await page.goto('/#/knowledge');
  await page.getByRole('combobox', { name: '知识库文件来源' }).click();
  await page.getByRole('option', { name: 'Rich notebook fixture', exact: true }).click();
  const notebook = page.getByLabel('笔记工作台', { exact: true });
  await notebook.getByRole('button', { name: '快速打开', exact: true }).click();
  await page.getByRole('dialog', { name: '快速打开', exact: true }).getByRole('button', { name: 'rich.md', exact: true }).click();
  await expect(notebook.locator('.katex')).toHaveCount(2);
  await expect(notebook.locator('[aria-label="笔记图表"] svg')).toHaveCount(1);
  await expect(notebook.getByText('图表无法安全渲染，源码已保留。')).toBeVisible();
  await expect(notebook.locator('script, foreignObject, iframe, img')).toHaveCount(0);
  const relations = notebook.getByRole('region', { name: '笔记关系能力', exact: true });
  await expect(relations.getByText('此固定版本尚未建立关系索引。').first()).toBeVisible();
  const favorite = notebook.getByRole('region', { name: '笔记收藏', exact: true });
  await favorite.getByRole('button', { name: '收藏笔记', exact: true }).click();
  await expect(favorite.getByText(/已收藏此笔记/)).toBeVisible();
  await favorite.getByRole('button', { name: '取消收藏', exact: true }).click();
  await expect(favorite.getByText(/尚未收藏此笔记.*修订 2/)).toBeVisible();
  await favorite.getByRole('button', { name: '收藏笔记', exact: true }).click();
  await expect(favorite.getByText(/已收藏此笔记.*修订 3/)).toBeVisible();
  await relations.getByRole('button', { name: '重建此版本关系索引', exact: true }).click();
  await expect(relations.getByText('target.md', { exact: true })).toBeVisible();
  await notebook.getByRole('button', { name: '快速打开', exact: true }).click();
  await page.getByRole('dialog', { name: '快速打开', exact: true }).getByRole('button', { name: 'target.md', exact: true }).click();
  await expect(relations.getByText('rich.md', { exact: true })).toBeVisible();
  const artifact = process.env.DRIVEBRIDGE_EVIDENCE_ARTIFACTS;
  if (artifact) await page.screenshot({ path: path.join(artifact, 'notebook-backlink.png'), animations: 'disabled' });
  expect(errors).toEqual([]);
  const rows = (await (await page.request.get('/api/v1/files?space_id=' + encodeURIComponent(space))).json()).data;
  expect(rows.find((file: { path: string }) => file.path === 'rich.md')).toBeTruthy();
});
