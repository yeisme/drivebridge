import { afterEach, expect, it, vi } from "vitest";
import { poll } from "./poll";

afterEach(() => { vi.useRealTimers(); vi.restoreAllMocks(); });
it.each([true, false])("gates foreground reads on session verification (allowed=%s)", async allowed => {
  vi.useFakeTimers();
  let hidden = true;
  vi.spyOn(document, "hidden", "get").mockImplementation(() => hidden);
  let finish!: () => void;
  const check = vi.fn(() => new Promise<void>((resolve, reject) => { finish = () => allowed ? resolve() : reject(Object.assign(new Error("unauthorized"), { status: 401 })); }));
  const read = vi.fn().mockResolvedValue("fresh");
  const denied = vi.fn();
  const stop = poll(read, vi.fn(), 10, denied, check);
  hidden = false; document.dispatchEvent(new Event("visibilitychange"));
  await vi.advanceTimersByTimeAsync(10);
  expect(check).toHaveBeenCalledTimes(1);
  expect(read).not.toHaveBeenCalled();
  finish();
  await vi.advanceTimersByTimeAsync(0);
  expect(read).toHaveBeenCalledTimes(allowed ? 1 : 0);
  expect(denied).toHaveBeenCalledTimes(allowed ? 0 : 1);
  stop();
});
it("pauses while hidden and rejects a pre-hide response after resuming", async () => {
  vi.useFakeTimers();
  let hidden = true;
  vi.spyOn(document, "hidden", "get").mockImplementation(() => hidden);
  let resolve!: (value: string) => void;
  const signals: AbortSignal[] = [];
  const read = vi.fn((signal: AbortSignal) => { signals.push(signal); return new Promise<string>(done => { resolve = done; }); });
  const accept = vi.fn();
  const stop = poll(read, accept, 10);
  await vi.advanceTimersByTimeAsync(100);
  expect(read).not.toHaveBeenCalled();
  hidden = false; document.dispatchEvent(new Event("visibilitychange"));
  await vi.advanceTimersByTimeAsync(10);
  expect(read).toHaveBeenCalledTimes(1);
  const oldResolve = resolve;
  hidden = true; document.dispatchEvent(new Event("visibilitychange"));
  expect(signals[0].aborted).toBe(true);
  await vi.advanceTimersByTimeAsync(100);
  expect(read).toHaveBeenCalledTimes(1);
  hidden = false; document.dispatchEvent(new Event("visibilitychange"));
  await vi.advanceTimersByTimeAsync(10);
  expect(read).toHaveBeenCalledTimes(2);
  oldResolve("stale");
  await vi.advanceTimersByTimeAsync(0);
  expect(accept).not.toHaveBeenCalled();
  resolve("fresh");
  await vi.advanceTimersByTimeAsync(0);
  expect(accept).toHaveBeenCalledWith("fresh");
  expect(vi.getTimerCount()).toBe(1);
  stop();
  document.dispatchEvent(new Event("visibilitychange"));
  expect(vi.getTimerCount()).toBe(0);
});
it.each([401, 403])("stops automatic polling after HTTP %s even across visibility changes", async status => {
  vi.useFakeTimers();
  const read = vi.fn().mockRejectedValue(Object.assign(new Error("request_failed"), { status }));
  const accept = vi.fn();
  const denied = vi.fn();
  const stop = poll(read, accept, 10, denied);
  await vi.advanceTimersByTimeAsync(100);
  document.dispatchEvent(new Event("visibilitychange"));
  await vi.advanceTimersByTimeAsync(100);
  expect(read).toHaveBeenCalledTimes(1);
  expect(accept).not.toHaveBeenCalled();
  expect(denied).toHaveBeenCalledTimes(1);
  expect(denied).toHaveBeenCalledWith(expect.objectContaining({ status }));
  expect(vi.getTimerCount()).toBe(0);
  stop();
});
it("never overlaps reads and waits after each completion", async () => {
  vi.useFakeTimers();
  let resolve!: (value: string) => void;
  const read = vi.fn(() => new Promise<string>(done => { resolve = done; }));
  const accept = vi.fn();
  const stop = poll(read, accept, 4000);
  await vi.advanceTimersByTimeAsync(4000);
  expect(read).toHaveBeenCalledTimes(1);
  await vi.advanceTimersByTimeAsync(20000);
  expect(read).toHaveBeenCalledTimes(1);
  resolve("first");
  await vi.advanceTimersByTimeAsync(0);
  expect(accept).toHaveBeenCalledWith("first");
  await vi.advanceTimersByTimeAsync(3999);
  expect(read).toHaveBeenCalledTimes(1);
  await vi.advanceTimersByTimeAsync(1);
  expect(read).toHaveBeenCalledTimes(2);
  stop();
});
it("aborts and fences a late result without scheduling another tick", async () => {
  vi.useFakeTimers();
  let resolve!: (value: string) => void;
  let signal!: AbortSignal;
  const read = vi.fn((value: AbortSignal) => { signal = value; return new Promise<string>(done => { resolve = done; }); });
  const accept = vi.fn();
  const stop = poll(read, accept, 10);
  await vi.advanceTimersByTimeAsync(10);
  stop();
  expect(signal.aborted).toBe(true);
  resolve("stale");
  await vi.advanceTimersByTimeAsync(100);
  expect(accept).not.toHaveBeenCalled();
  expect(read).toHaveBeenCalledTimes(1);
  expect(vi.getTimerCount()).toBe(0);
});
it("schedules the next read with the cadence updated by the accepted projection", async () => {
  vi.useFakeTimers();
  let delay = 2000;
  const read = vi.fn().mockResolvedValue("completed");
  const stop = poll(read, () => { delay = 30000; }, () => delay);
  await vi.advanceTimersByTimeAsync(2000);
  expect(read).toHaveBeenCalledTimes(1);
  await vi.advanceTimersByTimeAsync(29999);
  expect(read).toHaveBeenCalledTimes(1);
  await vi.advanceTimersByTimeAsync(1);
  expect(read).toHaveBeenCalledTimes(2);
  stop();
});
it("retains the old projection after failure and retries only the read", async () => {
  vi.useFakeTimers();
  vi.spyOn(Math, "random").mockReturnValue(0);
  const read = vi.fn().mockRejectedValueOnce(new Error("offline")).mockResolvedValue("recovered");
  const accept = vi.fn();
  const stop = poll(read, accept, 10);
  await vi.advanceTimersByTimeAsync(10);
  expect(accept).not.toHaveBeenCalled();
  await vi.advanceTimersByTimeAsync(1999);
  expect(read).toHaveBeenCalledTimes(1);
  await vi.advanceTimersByTimeAsync(1);
  expect(accept).toHaveBeenCalledWith("recovered");
  await vi.advanceTimersByTimeAsync(10);
  expect(read).toHaveBeenCalledTimes(3);
  stop();
  expect(vi.getTimerCount()).toBe(0);
});
