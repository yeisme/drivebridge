// Host secrets/path models deliberately stay outside web generated artifacts.
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { mkdir } from 'node:fs/promises';
import { applyArtifacts } from '../../web/scripts/contract-artifacts.mjs';
import openapiTS, { astToString } from 'openapi-typescript';
const root = fileURLToPath(new URL('../../', import.meta.url));
const check = process.argv.slice(2);
if (check.length > 1 || check.length && check[0] !== '--check') throw new Error('Usage: host-contracts.mjs [--check]');
if (/(?:^|\s)-race(?:\s|=|$)/.test(process.env.GOFLAGS || '')) throw new Error('Race instrumentation is not authorized.');
const schemas = JSON.parse(execFileSync('go', ['run', './cmd/drivebridge', 'desktop', 'schema'], {
  cwd: root, encoding: 'utf8', timeout: 120000, maxBuffer: 1024 * 1024,
  env: { ...process.env, CGO_ENABLED: '0', GOWORK: 'off' },
}));
if (Object.keys(schemas).sort().join() !== 'HostBootstrap,HostCancel,HostEvent,HostSelection') throw new Error('Host schema export changed unexpectedly.');
const document = { openapi: '3.1.0', info: { title: 'Private desktop host', version: 'v1alpha1' }, paths: {}, components: { schemas } };
const output = new URL('../src/generated/', import.meta.url);
const files = {
  'host-schemas.json': JSON.stringify(schemas, null, 2) + '\n',
  'host.ts': '// Generated by desktop schema. Main process only; never import into renderer/preload.\n' + astToString(await openapiTS(document)),
};
await mkdir(output, { recursive: true });
await applyArtifacts(fileURLToPath(output), files, check.length > 0);
console.log(check.length ? 'Private host contracts match Go.' : 'Private host contracts generated.');
